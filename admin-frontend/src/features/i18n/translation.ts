function translateWithPatterns(
  text: string,
  patterns: Array<{ pattern: RegExp; replace: (...args: string[]) => string }>,
) {
  for (const item of patterns) {
    const match = text.match(item.pattern)
    if (match) {
      return item.replace(...match)
    }
  }

  return text
}

export function translateText(text: string, language: AppLanguage) {
  if (!text) {
    return text
  }

  if (language === 'en') {
    return zhToEnMap[text] ?? translateWithPatterns(text, zhToEnPatterns)
  }

  return enToZhMap[text] ?? translateWithPatterns(text, enToZhPatterns)
}

export function pickText(language: AppLanguage, zh: string, en: string) {
  return language === 'en' ? en : zh
}
